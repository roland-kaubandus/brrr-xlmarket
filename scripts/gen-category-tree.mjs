#!/usr/bin/env node
/**
 * gen-category-tree.mjs — generate storefront/lib/category-tree.generated.json
 * from taxonomy.yaml.
 *
 * The tree is the SSoT for:
 *   - category page layout (breadcrumb, sibling list, thumbnail row)
 *   - MegaMenu N-level drill
 *   - category image lookup (replaces category-images.json indirection)
 *   - JSON-LD CollectionPage + BreadcrumbList
 *
 * Each node:
 *   {
 *     handle, name_et, name_en,
 *     level (1|2|3),
 *     parent_handle,
 *     child_handles[],
 *     image_path: string | null,    // /cat-thumbs/<slug>.webp or null
 *     image_source: "direct" | "alias" | "fuzzy" | "none",
 *   }
 *
 * Image resolution priority (per §3.5 and the image coverage invariant):
 *   1. direct  — <handle>.webp exists in public/cat-thumbs/
 *   2. alias   — taxonomy.yaml node has `image_alias: <legacy-slug>` and that file exists
 *   3. fuzzy   — every >=4-char word of handle appears in some legacy key (single unambiguous hit)
 *   4. none    — frontend renders SVG fallback (Lucide icon of the L1 ancestor)
 *
 * Legacy category-images.json is still loaded for backward compat with
 * storefront/components/MegaMenu.tsx THUMB_OVERRIDES and HomeBentoGrid,
 * but the new autoritative pointer is node.image_path.
 *
 * Usage:
 *   node scripts/gen-category-tree.mjs
 *   node scripts/gen-category-tree.mjs --check      # exit 1 if drifts
 *   node scripts/gen-category-tree.mjs --report     # print coverage table
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import yaml from "js-yaml"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const YAML_PATH = resolve(ROOT, "backend/src/data/taxonomy.yaml")
const ALIAS_PATH = resolve(ROOT, "backend/src/data/taxonomy-image-aliases.yaml")
const OUT_PATH = resolve(ROOT, "storefront/lib/category-tree.generated.json")
// SEISUND-silt SSoT: fixed_l2 mainide (Outlet) L2-lapsed → toote-sildi tekst per-locale.
// Klient (VevorProductCard/ProductContent) risutab toote category_handles nende võtmetega.
// Genereeritud siit → nimi ei vanane kunagi (nt L2 ümbernimetus levib automaatselt).
const OUTLET_LABELS_PATH = resolve(ROOT, "storefront/lib/outlet-labels.generated.json")
const LEGACY_IMG_PATH = resolve(ROOT, "storefront/lib/category-images.json")
const CAT_THUMBS_DIR = resolve(ROOT, "storefront/public/cat-thumbs")
const COUNTS_PATH = resolve(ROOT, "storefront/lib/category-counts.generated.json")
// L3-lehed, millel on 0 live-toodet (build-cat-thumbs-l3.mjs väljund). Neil EI SAA pilti genereerida
// (pole toodet) → ikoon-fallback on õige lõppseis. INV-20 aktsepteerib productless=true sõlme ilma pildita.
const PRODUCTLESS_PATH = resolve(ROOT, "scripts/data/productless-leaves.json")

function loadTaxonomy() {
  const doc = yaml.load(readFileSync(YAML_PATH, "utf8"))
  if (!doc?.l1 || !Array.isArray(doc.l1)) {
    throw new Error("taxonomy.yaml: missing or invalid `l1`")
  }
  return doc
}

function loadLegacyImageKeys() {
  if (!existsSync(LEGACY_IMG_PATH)) return new Set()
  const map = JSON.parse(readFileSync(LEGACY_IMG_PATH, "utf8"))
  return new Set(Object.keys(map))
}

function loadAliasMap() {
  if (!existsSync(ALIAS_PATH)) return {}
  const doc = yaml.load(readFileSync(ALIAS_PATH, "utf8")) || {}
  const map = {}
  for (const [k, v] of Object.entries(doc)) {
    if (typeof v === "string") map[k] = v
  }
  return map
}

function loadCounts() {
  // Meili product-volume snapshot (v4-keyed), regenerated by
  // gen-category-counts.mjs after each reindex. Drives the representativeness
  // ordering below — same signal the featured cards (menu-data.resolveUsable)
  // use. If missing/stale-empty, countOf() returns 0 for all → inheritance
  // degrades gracefully to leftmost order (previous behaviour).
  if (!existsSync(COUNTS_PATH)) return {}
  try {
    const doc = JSON.parse(readFileSync(COUNTS_PATH, "utf8"))
    return doc.counts || {}
  } catch {
    return {}
  }
}

function loadProductlessSet() {
  if (!existsSync(PRODUCTLESS_PATH)) return new Set()
  const doc = JSON.parse(readFileSync(PRODUCTLESS_PATH, "utf8"))
  return new Set(Array.isArray(doc.handles) ? doc.handles : [])
}

function loadThumbFiles() {
  if (!existsSync(CAT_THUMBS_DIR)) return new Set()
  return new Set(
    readdirSync(CAT_THUMBS_DIR)
      .filter((f) => f.endsWith(".webp"))
      .map((f) => f.replace(/\.webp$/, ""))
  )
}

function pickImage(handle, aliasHint, legacyKeys, thumbFiles) {
  // Only accept keys that are BOTH in legacy map AND have a file on disk
  // (or just have a file on disk, if legacy map is absent). This prevents
  // pointers to non-existent files, which is what INV-21 catches.
  const exists = (key) => thumbFiles.has(key)

  // 1. direct match on disk
  if (exists(handle)) {
    return { image_path: `/cat-thumbs/${handle}.webp`, image_source: "direct" }
  }

  // 2. explicit alias from yaml
  if (aliasHint && exists(aliasHint)) {
    return { image_path: `/cat-thumbs/${aliasHint}.webp`, image_source: "alias" }
  }

  // 3. fuzzy single-hit match (only against files actually on disk)
  const words = handle.split("-").filter((w) => w.length >= 4)
  if (words.length > 0 && thumbFiles.size > 0) {
    const candidates = []
    for (const k of thumbFiles) {
      if (words.every((w) => k.includes(w))) candidates.push(k)
    }
    if (candidates.length === 1) {
      return { image_path: `/cat-thumbs/${candidates[0]}.webp`, image_source: "fuzzy" }
    }
  }

  // Suppress unused param lint
  void legacyKeys
  return { image_path: null, image_source: "none" }
}

function buildTree(doc) {
  const nodes = {}
  const order = []
  const legacyKeys = loadLegacyImageKeys()
  const thumbFiles = loadThumbFiles()
  const aliasMap = loadAliasMap()

  function add(handle, attrs) {
    if (nodes[handle]) return
    nodes[handle] = { handle, ...attrs }
    order.push(handle)
  }

  // Recursive walker — supports L1..Ln (bootstrap-v3 uses up to L7).
  // Each node in YAML is: { slug, name_en, name_et?, description_en?, description_et?,
  //                         tagline_en?, tagline_et?, image_alias?, subs?: [child...] }
  function walk(node, level, parentHandle, conceptOnly = false) {
    const handle = typeof node === "string" ? node : node.slug
    if (!handle) return
    const isObj = typeof node === "object" && node !== null
    const nameEn = isObj
      ? (node.name_en || handle)
      : handle.split("-").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(" ")
    const nameEt = isObj ? (node.name_et || nameEn) : nameEn
    const alias = (isObj ? node.image_alias : null) || aliasMap[handle]
    // concept_only (Outlet, Tarmo 2026-09-17): SEISUND-kategooria, MITTE tüüp.
    // Ei tohi kanda toote-pilti (eksitab: "Outlet = tuulikud?"). Sunni image=none
    // kogu alampuul → frontend kuvab kontseptuaalse ikooni (BadgePercent).
    // Päritav: kui L1 on concept_only, on ka L2/L3 seda. Post-pass jätab need vahele.
    const isConcept = conceptOnly || (isObj && node.concept_only === true)
    const img = isConcept
      ? { image_path: null, image_source: "none" }
      : pickImage(handle, alias, legacyKeys, thumbFiles)
    const subs = isObj ? (node.subs || []) : []
    const childHandles = subs.map((s) => (typeof s === "string" ? s : s.slug)).filter(Boolean)

    const attrs = {
      name_en: nameEn,
      name_et: nameEt,
      level,
      parent_handle: parentHandle,
      child_handles: childHandles,
      ...img,
    }
    if (isConcept) attrs.concept_only = true
    // fixed_l2 (Osa 46): L1-only, NOT inherited (reads node.fixed_l2 directly, not
    // the conceptOnly-style param). Homepage box shows ALL L2 of this main (even
    // empty) — see getHomepageL1Nodes. Orthogonal to concept_only (image layer).
    if (isObj && node.fixed_l2 === true) attrs.fixed_l2 = true
    if (isObj && node.description_en != null) attrs.description_en = node.description_en
    if (isObj && node.description_et != null) attrs.description_et = node.description_et
    if (isObj && node.tagline_en != null) attrs.tagline_en = node.tagline_en
    if (isObj && node.tagline_et != null) attrs.tagline_et = node.tagline_et
    add(handle, attrs)

    for (const child of subs) walk(child, level + 1, handle, isConcept)
  }

  for (const l1 of doc.l1) walk(l1, 1, null)

  // Post-pass: inherit images from descendants for parents that ended up
  // without their own image (an L2 without a photo borrows from its subtree;
  // same for L3←L4, etc). Prevents the "some tiles missing" look.
  //
  // Donor selection = highest product-VOLUME representative, NOT leftmost.
  //   #3: an L1 like Tööriistad borrows the photo of its heaviest-selling
  //       branch's leaf (a representative product), not a random leftmost one.
  //   Consistency: same volume signal (countOf) the featured cards use
  //       (menu-data.resolveUsable) — one strategy for node image_path + cards.
  //
  // Plus DE-DUP: a parent's inherited image must differ from every DIRECT
  // child's displayed image (fixes the "parent == child same photo" pattern,
  // e.g. Dekoratsioonid == kunsttaimed == puud). If the heaviest representative
  // collides with a shown child, step to the next-heaviest distinct photo.
  const counts = loadCounts()
  const countOf = (h) => counts[h] ?? 0

  // Snapshot of nodes that own a REAL (non-inherited) photo after walk —
  // inheritance only ever borrows real photos, never a borrowed one.
  const hasDirect = new Set()
  for (const h of order) if (nodes[h].image_path) hasDirect.add(h)

  // All real-photo donors in a node's subtree, heaviest-count first,
  // de-duplicated by image_path (heaviest donor per distinct photo wins).
  function rankedDescendantImages(node) {
    const out = []
    const seenImg = new Set()
    function rec(n) {
      if (hasDirect.has(n.handle) && !seenImg.has(n.image_path)) {
        seenImg.add(n.image_path)
        out.push({ image_path: n.image_path, donor: n.handle })
      }
      const kids = (n.child_handles || [])
        .map((h) => nodes[h])
        .filter(Boolean)
        .sort((a, b) => countOf(b.handle) - countOf(a.handle))
      for (const k of kids) rec(k)
    }
    rec(node)
    return out
  }

  // Deepest level first so a parent sees its children's FINAL (post-dedup)
  // displayed images when it de-dups against them.
  const byLevelDesc = [...order].sort((a, b) => (nodes[b].level || 0) - (nodes[a].level || 0))
  for (const handle of byLevelDesc) {
    const n = nodes[handle]
    if (hasDirect.has(handle)) continue
    // concept_only (Outlet): SEISUND-kategooria ei päri KUNAGI toote-pilti, ka siis
    // kui alampuus tekib toode+thumb. Jääb image_source=none → ikoon-fallback.
    if (n.concept_only) continue
    const ranked = rankedDescendantImages(n)
    if (ranked.length === 0) continue

    // Images the direct children will actually display (their final image_path).
    const childImgs = new Set()
    for (const ch of n.child_handles || []) {
      const c = nodes[ch]
      if (c && c.image_path) childImgs.add(c.image_path)
    }

    // Heaviest representative that differs from every shown child; if all
    // collide (subtree has a single distinct photo), fall back to heaviest.
    const pick = ranked.find((r) => !childImgs.has(r.image_path)) || ranked[0]
    n.image_path = pick.image_path
    n.image_source = "inherited"
    n.image_donor = pick.donor
  }

  // Productless-stamp: leaf ilma pildita, mis on tootetute-loendis (Meilis 0 live-toodet) → ikoon-fallback
  // on õige lõppseis (mitte bug). INV-20 aktsepteerib productless=true. Iseparanduv: kui leaf saab tooteid,
  // kaob järgmisel pildi-jooksul loendist ja INV-20 nõuab pilti.
  const productlessSet = loadProductlessSet()
  for (const handle of order) {
    const n = nodes[handle]
    if (!n.image_path && productlessSet.has(handle)) n.productless = true
  }

  return {
    generated_at: new Date().toISOString(),
    nodes,
    order,
  }
}

function report(tree) {
  const nodes = Object.values(tree.nodes)
  const maxLvl = Math.max(...nodes.map((n) => n.level || 1))
  const rows = []
  for (let lvl = 1; lvl <= maxLvl; lvl++) {
    const ns = nodes.filter((n) => n.level === lvl)
    if (ns.length === 0) continue
    const bySrc = { direct: 0, alias: 0, fuzzy: 0, inherited: 0, none: 0 }
    for (const n of ns) bySrc[n.image_source] = (bySrc[n.image_source] || 0) + 1
    const covered = ns.length - bySrc.none
    rows.push({ lvl, total: ns.length, covered, ...bySrc })
  }
  console.log("Image coverage per level:")
  console.log("lvl | total | covered | direct | alias | fuzzy | inherited | none")
  for (const r of rows) {
    console.log(
      `L${r.lvl}  | ${String(r.total).padEnd(5)} | ${String(r.covered).padEnd(7)} | ${String(r.direct).padEnd(6)} | ${String(r.alias).padEnd(5)} | ${String(r.fuzzy).padEnd(5)} | ${String(r.inherited).padEnd(9)} | ${r.none}`
    )
  }
  const missing = nodes.filter((n) => n.image_source === "none").map((n) => n.handle)
  if (missing.length > 0) {
    console.log(`\n${missing.length} nodes with no image (will render SVG fallback)`)
  }
}

function main() {
  const doc = loadTaxonomy()
  const tree = buildTree(doc)
  const json = JSON.stringify(tree, null, 2) + "\n"

  if (process.argv.includes("--check")) {
    // Compare structural content only (ignore generated_at timestamp).
    const existingRaw = readFileSync(OUT_PATH, "utf8")
    const existing = JSON.parse(existingRaw)
    const { generated_at: _a, ...existingCore } = existing
    const { generated_at: _b, ...generatedCore } = tree
    if (JSON.stringify(existingCore) !== JSON.stringify(generatedCore)) {
      console.error("DRIFT: " + OUT_PATH + " out of sync with " + YAML_PATH)
      process.exit(1)
    }
    console.log("OK: " + OUT_PATH + " matches taxonomy.yaml")
    return
  }

  if (process.argv.includes("--report")) {
    report(tree)
    return
  }

  writeFileSync(OUT_PATH, json)
  console.log("Wrote " + Object.keys(tree.nodes).length + " nodes to " + OUT_PATH)

  // SEISUND-silt map: iga fixed_l2 maini (Outlet) L2-laps → sildi tekst.
  // Ainult L2 (otsesed lapsed) — silt ütleb TOOTE seisundi (Kahjustatud pakend /
  // Defektiga toode / Leiunurk), mitte sügavamat tüüpi. Toode päritakse handle'i
  // (stabiilne slug) järgi; nimi tuleb SSoT-st → ümbernimetus levib ise.
  const outletLabels = {}
  for (const h of tree.order) {
    const n = tree.nodes[h]
    if (n.fixed_l2 !== true) continue
    for (const ch of n.child_handles) {
      const c = tree.nodes[ch]
      if (!c) continue
      outletLabels[ch] = { et: c.name_et || c.name_en, en: c.name_en, main: h }
    }
  }
  writeFileSync(OUTLET_LABELS_PATH, JSON.stringify({ generated_at: tree.generated_at, labels: outletLabels }, null, 2) + "\n")
  console.log("Wrote " + Object.keys(outletLabels).length + " SEISUND labels to " + OUTLET_LABELS_PATH)

  report(tree)
}

main()
